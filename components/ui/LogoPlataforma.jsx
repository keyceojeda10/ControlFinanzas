const LOGO_COMPONENTS = {
  nequi: NequiIcon,
  daviplata: DaviplataIcon,
  bancolombia: BancolombiaIcon,
}

const PLATAFORMAS = {
  nequi: {
    color: '#DA0081',
    bg: 'color-mix(in srgb, #DA0081 14%, transparent)',
    label: 'Nequi',
  },
  daviplata: {
    color: '#E01A19',
    bg: 'color-mix(in srgb, #E01A19 14%, transparent)',
    label: 'Daviplata',
  },
  bancolombia: {
    color: '#002A5C',
    bg: 'color-mix(in srgb, #002A5C 14%, transparent)',
    label: 'Bancolombia',
  },
}

export function getPlataformaInfo(plataforma) {
  if (!plataforma) return null
  const key = plataforma.toLowerCase().trim()
  return PLATAFORMAS[key] || null
}

export function PlataformaIcon({ plataforma, size = 14 }) {
  if (!plataforma) return null
  const key = plataforma.toLowerCase().trim()
  const Logo = LOGO_COMPONENTS[key]
  if (!Logo) return null
  return (
    <span className="inline-flex items-center justify-center shrink-0" style={{ width: size, height: size }}>
      <Logo size={size} />
    </span>
  )
}

export function metodoInfo(pago) {
  if (pago?.metodoPago === 'transferencia') {
    const plat = getPlataformaInfo(pago?.plataforma)
    return {
      label: pago?.plataforma || 'Transferencia',
      color: plat?.color || 'var(--cf-ink-2)',
      bg: plat?.bg || 'color-mix(in srgb, var(--cf-ink-2) 12%, transparent)',
      plataforma: pago?.plataforma || null,
    }
  }
  if (pago?.metodoPago === 'efectivo') {
    return {
      label: 'Efectivo',
      color: 'var(--cf-green-dark)',
      bg: 'color-mix(in srgb, var(--cf-green-dark) 12%, transparent)',
      plataforma: null,
    }
  }
  return null
}

export default PLATAFORMAS
